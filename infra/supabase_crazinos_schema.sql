create schema if not exists crazinos;
revoke all on schema crazinos from public, anon, authenticated;

-- ---------- Layer 1: core tables ----------
create table if not exists crazinos.platforms (
  id bigint generated by default as identity primary key,
  platform_name text not null unique check (length(trim(platform_name)) > 0),
  status text not null default 'Active' check (status in ('Active','Inactive')),
  created_at timestamp not null default (now() at time zone 'Asia/Kolkata')
);

create table if not exists crazinos.kits (
  id bigint generated by default as identity primary key,
  kit_name text not null check (length(trim(kit_name)) > 0),
  sku text not null unique check (length(trim(sku)) > 0),
  description text not null default '',
  category text not null default 'General',
  cost_price numeric(12,2) check (cost_price is null or cost_price >= 0),
  default_selling_price numeric(12,2) not null check (default_selling_price >= 0),
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  image text not null default '',
  status text not null default 'Active' check (status in ('Active','Inactive')),
  created_at timestamp not null default (now() at time zone 'Asia/Kolkata'),
  updated_at timestamp not null default (now() at time zone 'Asia/Kolkata')
);

create table if not exists crazinos.sales (
  id bigint generated by default as identity primary key,
  kit_id bigint not null references crazinos.kits(id) on delete restrict,
  platform_id bigint not null references crazinos.platforms(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  selling_price_at_sale numeric(12,2) not null check (selling_price_at_sale >= 0),
  cost_price_at_sale numeric(12,2) check (cost_price_at_sale is null or cost_price_at_sale >= 0),
  total_amount numeric(14,2) not null,
  estimated_profit numeric(14,2),
  sale_date timestamp not null,
  sale_day date generated always as (sale_date::date) stored,
  created_at timestamp not null default (now() at time zone 'Asia/Kolkata'),
  updated_at timestamp not null default (now() at time zone 'Asia/Kolkata')
);

create table if not exists crazinos.reports (
  id bigint generated by default as identity primary key,
  report_type text not null check (report_type in ('daily','weekly','monthly','annual','custom')),
  start_date date not null,
  end_date date not null,
  generated_at timestamp not null default (now() at time zone 'Asia/Kolkata'),
  check (end_date >= start_date)
);

create table if not exists crazinos.settings (
  key text primary key,
  value text not null
);

-- ---------- Layer 2: indexes ----------
create index if not exists sales_sale_day_idx on crazinos.sales (sale_day);
create index if not exists sales_kit_day_idx on crazinos.sales (kit_id, sale_day);
create index if not exists sales_platform_day_idx on crazinos.sales (platform_id, sale_day);
create index if not exists reports_generated_at_idx on crazinos.reports (generated_at desc);

-- ---------- Layer 3: integrity triggers ----------
create or replace function crazinos.compute_sale_amounts()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.total_amount := round(new.quantity * new.selling_price_at_sale, 2);
  if new.cost_price_at_sale is null then
    new.estimated_profit := null;
  else
    new.estimated_profit := round((new.selling_price_at_sale - new.cost_price_at_sale) * new.quantity, 2);
  end if;
  return new;
end $$;

drop trigger if exists sales_compute_amounts on crazinos.sales;
create trigger sales_compute_amounts
before insert or update of quantity, selling_price_at_sale, cost_price_at_sale on crazinos.sales
for each row execute function crazinos.compute_sale_amounts();

create or replace function crazinos.touch_updated_at()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.updated_at := now() at time zone 'Asia/Kolkata';
  return new;
end $$;

drop trigger if exists kits_touch_updated_at on crazinos.kits;
create trigger kits_touch_updated_at before update on crazinos.kits
for each row execute function crazinos.touch_updated_at();

drop trigger if exists sales_touch_updated_at on crazinos.sales;
create trigger sales_touch_updated_at before update on crazinos.sales
for each row execute function crazinos.touch_updated_at();

-- ---------- Layer 4: reporting views ----------
create or replace view crazinos.v_sales_detailed with (security_invoker = true) as
select s.id, s.sale_date, s.sale_day, s.quantity, s.selling_price_at_sale, s.cost_price_at_sale,
       s.total_amount, s.estimated_profit,
       k.id as kit_id, k.kit_name, k.sku, k.category,
       p.id as platform_id, p.platform_name
from crazinos.sales s
join crazinos.kits k on k.id = s.kit_id
join crazinos.platforms p on p.id = s.platform_id;

create or replace view crazinos.v_daily_summary with (security_invoker = true) as
select sale_day,
       sum(quantity)::bigint as total_kits_sold,
       count(*)::bigint as total_orders,
       sum(total_amount) as total_revenue,
       coalesce(sum(estimated_profit), 0) as total_profit
from crazinos.sales
group by sale_day;

